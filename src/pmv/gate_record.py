"""Gate decision records: closed v1 schema, canonical rendering, and lineage rules.

Pure functions; no filesystem or Git access. A gate record is one generated Markdown file,
``docs/decisions/gates/<gate_id>_<record_id>.md``: a fixed header, a deterministic summary,
and one fenced canonical JSON record. The verifier parses the JSON, re-renders the whole
file, and requires byte equality, so no hand edit (including to the summary) survives. The
authoritative hash of a record is the SHA-256 of the exact file bytes; it is never stored
inside the record itself.

The record holds only enums, identifiers, hashes, timestamps, and repository paths. Human
rationale lives in separately tracked documents referenced by path and SHA-256.
"""

