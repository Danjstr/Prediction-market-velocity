@dataclass(frozen=True, slots=True)
class LineageKey:
    gate_id: str
    cycle_id: str | None
    candidate_id: str | None


@dataclass(frozen=True, slots=True)
class GateRecord:
    """A validated v1 record. ``document`` is the canonical JSON object."""

    document: Mapping[str, object]

    @property
    def record_id(self) -> str:
        return str(self.document["record_id"])

    @property
    def gate_id(self) -> str:
        return str(self.document["gate_id"])

    @property
    def decision(self) -> Decision:
        return Decision(str(self.document["decision"]))

    @property
    def decided_at(self) -> str:
        return str(self.document["decided_at"])

    @property
    def lineage(self) -> LineageKey:
        scope = _mapping(self.document["scope"])
        cycle, candidate = scope["cycle_id"], scope["candidate_id"]
        return LineageKey(
            self.gate_id,
            None if cycle is None else str(cycle),
            None if candidate is None else str(candidate),
        )

    @property
    def supersedes(self) -> tuple[str, str] | None:
        value = self.document["supersedes"]
        if value is None:
            return None
        prior = _mapping(value)
        return str(prior["record_id"]), str(prior["record_sha256"])

    @property
    def file_name(self) -> str:
        return record_file_name(self.gate_id, self.record_id)


# ----- names -----


def record_file_name(gate_id: str, record_id: str) -> str:
    name = f"{GateId(gate_id).value}_{record_id}.md"
    if _FILE_NAME.fullmatch(name) is None:
        raise GateRecordError("the gate record file name is malformed")
    return name


def parse_file_name(name: str) -> tuple[str, str] | None:
    """Return (gate_id, record_id) for a valid record file name, else None."""
    match = _FILE_NAME.fullmatch(name)
    return None if match is None else (match[1], match[2])


def record_id_timestamp(record_id: str) -> str:
    """The canonical UTC timestamp embedded in a record ID."""
    stamp = record_id.split("_", 1)[0]
    return (
        f"{stamp[0:4]}-{stamp[4:6]}-{stamp[6:8]}T{stamp[9:11]}:{stamp[11:13]}:"
        f"{stamp[13:15]}.{stamp[16:22]}Z"
    )


def is_document_path(path: object) -> bool:
    """A tracked repository document: under docs/ or research/, or a governance file.

    Plain components only (no '.', '..', hidden names, or separators beyond '/'), and
    never inside the gate-record directory itself.
    """
    if not isinstance(path, str) or len(path) > 512:
        return False
    if path in GOVERNANCE_PATHS:
        return True
    parts = path.split("/")
    if parts[0] not in ("docs", "research") or len(parts) < 2:
        return False
    if path.startswith(GATES_DIR + "/"):
        return False
    return all(_PATH_COMPONENT.fullmatch(part) is not None for part in parts)


# ----- validation -----


def validate_record(document: Mapping[str, object]) -> GateRecord:
    """Validate a complete v1 record document (schema, canonical order, and semantics)."""
    _keys(
        document,
        {
            "schema",
            "schema_version",
            "record_id",
            "gate_id",
            "scope",
            "decided_at",
            "decision",
            "reasons",
            "findings",
            "reviews",
            "final_decision",
            "project",
            "experiment_ledger",
            "evidence",
            "supersedes",
        },
        "record",
    )
    if document["schema"] != SCHEMA:
        raise GateRecordError("the record schema is not pmv.gate_record")
    version = document["schema_version"]
    if type(version) is not int or version != SCHEMA_VERSION:
        raise GateRecordError("the record schema_version is not supported")
    record_id = document["record_id"]
    if not is_timestamp_id(record_id):
        raise GateRecordError("record_id is malformed")
    _enum(GateId, document["gate_id"], "gate_id")
    if not is_timestamp(document["decided_at"]):
        raise GateRecordError("decided_at is malformed")
    if record_id_timestamp(record_id) != document["decided_at"]:
        raise GateRecordError("record_id and decided_at disagree")
    scope = _mapping(document["scope"])
    _keys(scope, {"cycle_id", "candidate_id"}, "scope")
    for key in ("cycle_id", "candidate_id"):
        _optional(scope[key], is_identifier, f"scope.{key}")
    decision = Decision(_enum(Decision, document["decision"], "decision"))
    reasons = _strings(document["reasons"], "reasons")
    if decision is Decision.PASS and reasons:
        raise GateRecordError("a pass record has no reasons")
    if decision is Decision.FAIL:
        _require_reasons(reasons, FailReason, "fail")
    if decision is Decision.INCONCLUSIVE:
        _require_reasons(reasons, InconclusiveReason, "inconclusive")
    findings = _list(document["findings"], "findings")
    for finding in findings:
        _validate_finding(finding)
    reviews = _list(document["reviews"], "reviews")
    for review in reviews:
        _validate_review(review)
    _validate_final_decision(document["final_decision"])
    project = _validate_project(document["project"])
    pin = _validate_pin(document["experiment_ledger"])
    runs = _validate_evidence(document["evidence"], pin is not None)
    _validate_supersedes(document["supersedes"], str(record_id))
    if canonicalize(document) != document:
        raise GateRecordError("record lists must be in canonical order without duplicates")
    _reject_secret_looking(document)
    if decision is Decision.PASS:
        _pass_rules(findings, runs, project, _mapping(document["evidence"]))
    return GateRecord(dict(document))


def _pass_rules(
    findings: list[object],
    runs: list[Mapping[str, object]],
    project: Mapping[str, object],
    evidence: Mapping[str, object],
) -> None:
    for finding in findings:
        item = _mapping(finding)
        if item["severity"] == FindingSeverity.BLOCKING and item["status"] != (
            FindingStatus.RESOLVED
        ):
            raise GateRecordError(
                "pass requires every blocking finding to be resolved; "
                "accepted_by_owner does not resolve a blocker"
            )
    for run in runs:
        if RunRole(str(run["role"])) in ELIGIBILITY_ROLES and (
            run["state_at_pin"] != RunStateAtPin.COMPLETED or run["eligible_at_pin"] is not True
        ):
            raise GateRecordError(
                "pass requires candidate and supporting runs to be completed and "
                "evidence-eligible as of the pinned ledger head"
            )
    roles = {run["run_id"]: RunRole(str(run["role"])) for run in runs}
    for artifact in _list(evidence["artifacts"], "evidence.artifacts"):
        if roles.get(_mapping(artifact)["run_id"]) not in ELIGIBILITY_ROLES:
            raise GateRecordError(
                "pass artifacts must come from candidate or supporting runs that are "
                "evidence-eligible as of the pinned ledger head"
            )
    if project["tree_dirty"] is not False:
        raise GateRecordError("pass requires a clean project tree")
    checks = _list(evidence["checks"], "evidence.checks")
    if not any(
        _mapping(check)["check_id"] == CheckId.CHECK_SH
        and _mapping(check)["outcome"] == CheckOutcome.PASSED
        for check in checks
    ):
        raise GateRecordError("pass requires a passing check_sh run by the gate tool")


def _validate_finding(value: object) -> None:
    item = _mapping(value)
    _keys(item, {"finding_id", "severity", "status", "document"}, "finding")
    if not is_identifier(item["finding_id"]):
        raise GateRecordError("finding_id is malformed")
    _enum(FindingSeverity, item["severity"], "finding.severity")
    _enum(FindingStatus, item["status"], "finding.status")
    _optional_document(item["document"], REVIEW_DOCUMENT_KINDS)


def _validate_review(value: object) -> None:
    item = _mapping(value)
    _keys(item, {"role", "conclusion", "independence", "document"}, "review")
    _enum(ReviewerRole, item["role"], "review.role")
    _enum(ReviewConclusion, item["conclusion"], "review.conclusion")
    _enum(Independence, item["independence"], "review.independence")
    _optional_document(item["document"], REVIEW_DOCUMENT_KINDS)


def _validate_final_decision(value: object) -> None:
    item = _mapping(value)
    _keys(item, {"role", "approval_requirement", "approval_attested"}, "final_decision")
    if item["role"] != "project_owner":
        raise GateRecordError("final_decision.role must be project_owner")
    _enum(ApprovalRequirement, item["approval_requirement"], "approval_requirement")
    if item["approval_attested"] is not True:
        raise GateRecordError(
            "every v1 gate decision requires owner approval; the operator must attest that "
            "it occurred"
        )


def _validate_project(value: object) -> Mapping[str, object]:
    item = _mapping(value)
    _keys(item, {"commit", "tree_dirty", "dirty_tree_sha256", "governance", "configs"}, "project")
    commit = item["commit"]
    if not isinstance(commit, str) or _COMMIT.fullmatch(commit) is None:
        raise GateRecordError("project.commit is malformed")
    dirty = item["tree_dirty"]
    if not isinstance(dirty, bool):
        raise GateRecordError("project.tree_dirty must be a boolean")
    fingerprint = item["dirty_tree_sha256"]
    if dirty != (fingerprint is not None) or (
        fingerprint is not None and not is_sha256(fingerprint)
    ):
        raise GateRecordError("dirty_tree_sha256 is set exactly when the tree is dirty")
    governance = _list(item["governance"], "project.governance")
    for document in governance:
        _validate_document(document, (DocumentKind.GOVERNANCE,))
    if [_mapping(doc)["path"] for doc in governance] != list(GOVERNANCE_PATHS):
        raise GateRecordError("project.governance must pin exactly the four governance files")
    configs = _list(item["configs"], "project.configs")
    for config in configs:
        entry = _mapping(config)
        _keys(entry, {"path", "sha256"}, "config")
        path = entry["path"]
        if not isinstance(path, str) or _CONFIG_PATH.fullmatch(path) is None:
            raise GateRecordError("a config path is malformed")
        if not is_sha256(entry["sha256"]):
            raise GateRecordError("a config hash is malformed")
    return item


def _validate_pin(value: object) -> Mapping[str, object] | None:
    if value is None:
        return None
    item = _mapping(value)
    _keys(item, {"store_id", "ledger_seq", "entry_sha256", "checkpoint"}, "experiment_ledger")
    store_id = item["store_id"]
    if not isinstance(store_id, str) or _STORE_ID.fullmatch(store_id) is None:
        raise GateRecordError("experiment_ledger.store_id is malformed")
    if not is_non_negative_int(item["ledger_seq"]):
        raise GateRecordError("experiment_ledger.ledger_seq is malformed")
    if not is_sha256(item["entry_sha256"]):
        raise GateRecordError("experiment_ledger.entry_sha256 is malformed")
    if item["checkpoint"] is not None:
        checkpoint = _mapping(item["checkpoint"])
        _keys(checkpoint, {"ledger_seq", "entry_sha256", "committed_in_git"}, "checkpoint")
        seq, head = checkpoint["ledger_seq"], item["ledger_seq"]
        if not is_non_negative_int(seq) or not is_non_negative_int(head) or seq > head:
            raise GateRecordError("the checkpoint must be at or before the pinned head")
        if not is_sha256(checkpoint["entry_sha256"]):
            raise GateRecordError("checkpoint.entry_sha256 is malformed")
        if not isinstance(checkpoint["committed_in_git"], bool):
            raise GateRecordError("checkpoint.committed_in_git must be a boolean")
    return item


def _validate_evidence(value: object, pinned: bool) -> list[Mapping[str, object]]:
    evidence = _mapping(value)
    _keys(
        evidence,
        {"runs", "artifacts", "raw_captures", "documents", "checks", "holdout"},
        "evidence",
    )
    if _list(evidence["holdout"], "evidence.holdout"):
        raise GateRecordError(HOLDOUT_REJECTION)
    runs = [_mapping(item) for item in _list(evidence["runs"], "evidence.runs")]
    for run in runs:
        _keys(run, {"run_id", "role", "state_at_pin", "eligible_at_pin"}, "run")
        if not is_timestamp_id(run["run_id"]):
            raise GateRecordError("a run_id is malformed")
        _enum(RunRole, run["role"], "run.role")
        _enum(RunStateAtPin, run["state_at_pin"], "run.state_at_pin")
        if not isinstance(run["eligible_at_pin"], bool):
            raise GateRecordError("run.eligible_at_pin must be a boolean")
    artifacts = [_mapping(item) for item in _list(evidence["artifacts"], "evidence.artifacts")]
    for artifact in artifacts:
        _keys(artifact, {"run_id", "artifact_name", "sha256"}, "artifact")
        if not is_timestamp_id(artifact["run_id"]) or not is_sha256(artifact["sha256"]):
            raise GateRecordError("an artifact reference is malformed")
        name = artifact["artifact_name"]
        if not isinstance(name, str) or ARTIFACT_NAME.fullmatch(name) is None:
            raise GateRecordError("an artifact name is malformed")
    if (runs or artifacts) and not pinned:
        raise GateRecordError("run and artifact evidence requires a pinned experiment ledger")
    listed = {run["run_id"] for run in runs}
    if any(artifact["run_id"] not in listed for artifact in artifacts):
        raise GateRecordError("every artifact's producing run must be listed in evidence.runs")
    captures = [_mapping(item) for item in _list(evidence["raw_captures"], "evidence.raw_captures")]
    for capture in captures:
        _keys(capture, {"capture_id", "manifest_sha256"}, "raw capture")
        if not is_timestamp_id(capture["capture_id"]) or not is_sha256(capture["manifest_sha256"]):
            raise GateRecordError("a raw capture reference is malformed")
    documents = _list(evidence["documents"], "evidence.documents")
    for document in documents:
        _validate_document(document, EVIDENCE_DOCUMENT_KINDS)
    checks = [_mapping(item) for item in _list(evidence["checks"], "evidence.checks")]
    for check in checks:
        _keys(check, {"check_id", "outcome"}, "check")
        _enum(CheckId, check["check_id"], "check.check_id")
        _enum(CheckOutcome, check["outcome"], "check.outcome")
    return runs


def _validate_supersedes(value: object, record_id: str) -> None:
    if value is None:
        return
    item = _mapping(value)
    _keys(item, {"record_id", "record_sha256"}, "supersedes")
    if not is_timestamp_id(item["record_id"]) or not is_sha256(item["record_sha256"]):
        raise GateRecordError("supersedes is malformed")
    if item["record_id"] == record_id:
        raise GateRecordError("a record cannot supersede itself")


def _validate_document(value: object, kinds: Sequence[DocumentKind]) -> None:
    item = _mapping(value)
    _keys(item, {"path", "sha256", "kind"}, "document")
    if not is_document_path(item["path"]):
        raise GateRecordError("a document path is not an allowed repository document")
    if not is_sha256(item["sha256"]):
        raise GateRecordError("a document hash is malformed")
    kind = DocumentKind(_enum(DocumentKind, item["kind"], "document.kind"))
    if kind is DocumentKind.HOLDOUT_EVALUATION:
        raise GateRecordError(HOLDOUT_REJECTION)
    if kind not in kinds:
        raise GateRecordError("the document kind is not allowed here")
    if (kind is DocumentKind.GOVERNANCE) != (item["path"] in GOVERNANCE_PATHS):
        raise GateRecordError("governance documents are exactly the four governance files")


def _optional_document(value: object, kinds: Sequence[DocumentKind]) -> None:
    if value is not None:
        _validate_document(value, kinds)


def _require_reasons(reasons: list[str], enum: type[StrEnum], what: str) -> None:
    if not reasons:
        raise GateRecordError(f"a {what} record needs at least one reason")
    for reason in reasons:
        _enum(enum, reason, f"{what} reason")


# ----- canonical order -----


def _key(*values: object) -> bytes:
    return canonical_json({"k": list(values)})


def _ordered(
    items: object, key: Callable[[Mapping[str, object]], bytes], what: str
) -> list[object]:
    mappings = [_mapping(item) for item in _list(items, what)]
    ordered = sorted(mappings, key=key)
    keys = [key(item) for item in ordered]
    if len(set(keys)) != len(keys):
        raise GateRecordError(f"{what} must not contain duplicates")
    return list(ordered)


def canonicalize(document: Mapping[str, object]) -> dict[str, object]:
    """Return ``document`` with every list in its one canonical order.

    Raises GateRecordError on duplicates. The builder uses this, and validation requires a
    record to already be in this form, so equivalent records have identical bytes.
    """
    reasons = _strings(document["reasons"], "reasons")
    if len(set(reasons)) != len(reasons):
        raise GateRecordError("reasons must not contain duplicates")
    project = dict(_mapping(document["project"]))
    project["configs"] = _ordered(project["configs"], lambda c: _key(c["path"]), "configs")
    evidence = dict(_mapping(document["evidence"]))
    evidence["runs"] = _ordered(evidence["runs"], lambda r: _key(r["run_id"]), "runs")
    evidence["artifacts"] = _ordered(
        evidence["artifacts"], lambda a: _key(a["run_id"], a["artifact_name"]), "artifacts"
    )
    evidence["raw_captures"] = _ordered(
        evidence["raw_captures"], lambda c: _key(c["capture_id"]), "raw_captures"
    )
    evidence["documents"] = _ordered(evidence["documents"], lambda d: _key(d["path"]), "documents")
    evidence["checks"] = _ordered(evidence["checks"], lambda c: _key(c["check_id"]), "checks")
    return {
        **document,
        "reasons": sorted(reasons),
        "findings": _ordered(document["findings"], lambda f: _key(f["finding_id"]), "findings"),
        "reviews": _ordered(document["reviews"], lambda r: canonical_json(r), "reviews"),
        "project": project,
        "evidence": evidence,
    }


# ----- rendering and parsing -----


def render_record(record: GateRecord) -> bytes:
    """The complete canonical file bytes for ``record``."""
    document = record.document
    scope = _mapping(document["scope"])
    final = _mapping(document["final_decision"])
    project = _mapping(document["project"])
    pin = document["experiment_ledger"]
    evidence = _mapping(document["evidence"])
    supersedes = record.supersedes
    dash = "-"

    def code(value: object) -> str:
        return dash if value is None else f"`{value}`"

    def joined(values: Sequence[object]) -> str:
        return ", ".join(f"`{value}`" for value in values) if values else dash

    tree = (
        "clean"
        if project["tree_dirty"] is False
        else f"dirty, fingerprint `{project['dirty_tree_sha256']}`"
    )
    if pin is None:
        ledger_text = dash
    else:
        pinned = _mapping(pin)
        ledger_text = (
            f"store `{pinned['store_id']}`, seq `{pinned['ledger_seq']}`, "
            f"entry `{pinned['entry_sha256']}`"
        )
    lines = [
        f"# Gate record: {record.gate_id}",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Record ID | `{record.record_id}` |",
        f"| Gate | `{record.gate_id}` |",
        f"| Cycle | {code(scope['cycle_id'])} |",
        f"| Candidate | {code(scope['candidate_id'])} |",
        f"| Decision | **{record.decision.value.upper()}** |",
        f"| Decided at (UTC) | `{record.decided_at}` |",
        f"| Reasons | {joined(_list(document['reasons'], 'reasons'))} |",
        f"| Final decision role | `{final['role']}` |",
        f"| Owner approval | `{final['approval_requirement']}`; attested: "
        f"`{str(final['approval_attested']).lower()}` |",
        f"| Project commit | `{project['commit']}` ({tree}) |",
        f"| Experiment ledger | {ledger_text} |",
        "| Supersedes | "
        + (dash if supersedes is None else f"`{supersedes[0]}` (`{supersedes[1]}`)")
        + " |",
        "",
        "## Reviews",
        "",
        *_bullets(
            _list(document["reviews"], "reviews"),
            lambda r: (
                f"`{r['role']}`: `{r['conclusion']}` (`{r['independence']}`)"
                + _document_suffix(r["document"])
            ),
        ),
        "",
        "## Findings",
        "",
        *_bullets(
            _list(document["findings"], "findings"),
            lambda f: (
                f"`{f['finding_id']}`: `{f['severity']}`, `{f['status']}`"
                + _document_suffix(f["document"])
            ),
        ),
        "",
        "## Evidence",
        "",
        "Runs:",
        *_bullets(
            _list(evidence["runs"], "runs"),
            lambda r: (
                f"`{r['run_id']}` `{r['role']}`: `{r['state_at_pin']}`, eligible at pin: "
                f"`{str(r['eligible_at_pin']).lower()}`"
            ),
        ),
        "",
        "Artifacts:",
        *_bullets(
            _list(evidence["artifacts"], "artifacts"),
            lambda a: f"`{a['run_id']}` `{a['artifact_name']}` `{a['sha256']}`",
        ),
        "",
        "Raw captures:",
        *_bullets(
            _list(evidence["raw_captures"], "raw_captures"),
            lambda c: f"`{c['capture_id']}` manifest `{c['manifest_sha256']}`",
        ),
        "",
        "Documents:",
        *_bullets(
            _list(evidence["documents"], "documents"),
            lambda d: f"`{d['kind']}` `{d['path']}` `{d['sha256']}`",
        ),
        "",
        "Checks:",
        *_bullets(
            _list(evidence["checks"], "checks"),
            lambda c: f"`{c['check_id']}`: `{c['outcome']}`",
        ),
        "",
        "## Canonical record",
        "",
    ]
    body = "\n".join(lines) + "\n" + _FENCE_OPEN + canonical_json(document).decode("ascii")
    return (HEADER + body + _FENCE_CLOSE).encode("ascii")


def parse_record_file(data: bytes, name: str | None = None) -> GateRecord:
    """Parse and fully verify a record file: schema, semantics, and exact re-rendering."""
    try:
        text = data.decode("ascii")
    except UnicodeDecodeError:
        raise GateRecordError("a gate record file is not ASCII") from None
    start = text.rfind(_FENCE_OPEN)
    if not text.startswith(HEADER) or start == -1 or not text.endswith(_FENCE_CLOSE):
        raise GateRecordError("a gate record file does not have the generated layout")
    payload = text[start + len(_FENCE_OPEN) : -len(_FENCE_CLOSE)]
    try:
        document = parse_canonical_json(payload.encode("ascii"))
    except FormatError:
        raise GateRecordError("the gate record JSON is not canonical") from None
    record = validate_record(document)
    if render_record(record) != data:
        raise GateRecordError("the gate record file differs from its canonical rendering")
    if name is not None and name != record.file_name:
        raise GateRecordError("the gate record file name does not match its record")
    return record


def record_sha256(data: bytes) -> str:
    return sha256_hex(data)


# ----- lineage -----


@dataclass(frozen=True, slots=True)
class LineageMember:
    record: GateRecord
    sha256: str
    committed: bool


def verify_lineages(members: Sequence[LineageMember]) -> dict[LineageKey, LineageMember]:
    """Check every lineage; return each lineage's head.

    Each lineage (gate, cycle, candidate) has exactly one root and no forks; every
    predecessor exists, is in the same lineage, is committed, matches the named hash, and
    is older than its successor. Cycles are impossible to close without a hash fixpoint
    and are rejected explicitly anyway.
    """
    by_id: dict[str, LineageMember] = {}
    for member in members:
        if member.record.record_id in by_id:
            raise GateRecordError("two gate records share a record_id")
        by_id[member.record.record_id] = member
    successors: dict[str, str] = {}
    roots: dict[LineageKey, list[str]] = {}
    for member in members:
        record = member.record
        prior = record.supersedes
        if prior is None:
            roots.setdefault(record.lineage, []).append(record.record_id)
            continue
        predecessor = by_id.get(prior[0])
        if predecessor is None:
            raise GateRecordError("a gate record supersedes a record that does not exist")
        if predecessor.sha256 != prior[1]:
            raise GateRecordError("a superseded gate record does not match its recorded hash")
        if predecessor.record.lineage != record.lineage:
            raise GateRecordError("a gate record supersedes a record from another lineage")
        if not predecessor.committed:
            raise GateRecordError("a gate record supersedes an uncommitted record")
        if predecessor.record.record_id >= record.record_id:
            raise GateRecordError("a gate record supersedes a newer record")
        if prior[0] in successors:
            raise GateRecordError("a gate record has competing successors (a fork)")
        successors[prior[0]] = record.record_id
    heads: dict[LineageKey, LineageMember] = {}
    for key, ids in roots.items():
        if len(ids) != 1:
            raise GateRecordError("a gate lineage has more than one root record")
        current = ids[0]
        seen = {current}
        while current in successors:
            current = successors[current]
            if current in seen:
                raise GateRecordError("a gate lineage contains a cycle")
            seen.add(current)
        heads[key] = by_id[current]
    reachable = sum(_chain_length(successors, ids[0]) for ids in roots.values())
    if reachable != len(members):
        raise GateRecordError("a gate lineage contains a cycle or an unreachable record")
    return heads


def _chain_length(successors: Mapping[str, str], root: str) -> int:
    length, current, seen = 1, root, {root}
    while current in successors:
        current = successors[current]
        if current in seen:
            raise GateRecordError("a gate lineage contains a cycle")
        seen.add(current)
        length += 1
    return length


# ----- helpers -----


def _mapping(value: object) -> Mapping[str, object]:
    if not isinstance(value, Mapping):
        raise GateRecordError("a record field must be an object")
    return value


def _list(value: object, what: str) -> list[object]:
    if not isinstance(value, list):
        raise GateRecordError(f"{what} must be a list")
    return value


def _keys(value: Mapping[str, object], expected: set[str], what: str) -> None:
    if set(value) != expected:
        raise GateRecordError(f"{what} fields do not match the v1 schema")


def _enum(enum: type[StrEnum], value: object, what: str) -> str:
    if not isinstance(value, str) or value not in {item.value for item in enum}:
        raise GateRecordError(f"{what} is not a known value")
    return value


def _optional(value: object, check: Callable[[object], bool], what: str) -> None:
    if value is not None and not check(value):
        raise GateRecordError(f"{what} is malformed")


def _reject_secret_looking(value: object) -> None:
    """No string anywhere in a record may look like secret material."""
    if isinstance(value, str):
        if redact_text(value) != value:
            raise GateRecordError("a gate record value looks like secret material")
    elif isinstance(value, Mapping):
        for item in value.values():
            _reject_secret_looking(item)
    elif isinstance(value, list):
        for item in value:
            _reject_secret_looking(item)


def _strings(value: object, what: str) -> list[str]:
    items = _list(value, what)
    if not all(isinstance(item, str) for item in items):
        raise GateRecordError(f"{what} must be strings")
    return [str(item) for item in items]


def _bullets(items: Sequence[object], render: Callable[[Mapping[str, object]], str]) -> list[str]:
    if not items:
        return ["- none"]
    return [f"- {render(_mapping(item))}" for item in items]


def _document_suffix(value: object) -> str:
    if value is None:
        return ""
    document = _mapping(value)
    return f"; document `{document['path']}` `{document['sha256']}`"
