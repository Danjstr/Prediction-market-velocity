def test_the_schema_document_matches_the_python_validator() -> None:
    schema = json.loads(
        (Path(__file__).resolve().parents[2] / "schemas" / "gate_record_v1.json").read_text(
            encoding="ascii"
        )
    )
    valid = document()
    assert set(schema["required"]) == set(valid) == set(schema["properties"])
    properties = schema["properties"]
    assert properties["gate_id"]["enum"] == [item.value for item in gate_record.GateId]
    assert properties["decision"]["enum"] == [item.value for item in gate_record.Decision]
    assert properties["reasons"]["items"]["enum"] == [
        *(item.value for item in gate_record.FailReason),
        *(item.value for item in gate_record.InconclusiveReason),
    ]
    review = properties["reviews"]["items"]["properties"]
    assert review["role"]["enum"] == [item.value for item in gate_record.ReviewerRole]
    evidence = properties["evidence"]["properties"]
    assert set(evidence) == set(valid["evidence"])
    assert evidence["holdout"]["maxItems"] == 0
    assert evidence["runs"]["items"]["properties"]["role"]["enum"] == [
        item.value for item in gate_record.RunRole
    ]
    assert set(properties["project"]["required"]) == set(valid["project"])
    assert set(properties["final_decision"]["required"]) == set(valid["final_decision"])


