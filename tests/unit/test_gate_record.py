def document(**overrides: Any) -> dict[str, Any]:
    base: dict[str, Any] = {
        "decided_at": DECIDED_AT,
        "decision": "pass",
        "evidence": {
            "artifacts": [],
            "checks": [{"check_id": "check_sh", "outcome": "passed"}],
            "documents": [],
            "holdout": [],
            "raw_captures": [],
            "runs": [],
        },
        "experiment_ledger": None,
        "final_decision": {
            "approval_attested": True,
            "approval_requirement": "required",
            "role": "project_owner",
        },
        "findings": [],
        "gate_id": "gate_0",
        "project": {
            "commit": "c" * 40,
            "configs": [{"path": "configs/test.toml", "sha256": "1" * 64}],
            "dirty_tree_sha256": None,
            "governance": [
                {"kind": "governance", "path": path, "sha256": "2" * 64} for path in GOVERNANCE
            ],
            "tree_dirty": False,
        },
        "reasons": [],
        "record_id": RECORD_ID,
        "reviews": [
            {
                "conclusion": "recommend_pass",
                "document": {"kind": "review", "path": "docs/reviews/r1.md", "sha256": "3" * 64},
                "independence": "independent",
                "role": "reliability_red_team",
            }
        ],
        "schema": "pmv.gate_record",
        "schema_version": 1,
        "scope": {"candidate_id": None, "cycle_id": None},
        "supersedes": None,
    }
    base.update(overrides)
    return base


def with_evidence(**changes: Any) -> dict[str, Any]:
    base = document()
    base["evidence"] = {**base["evidence"], **changes}
    return base


def pinned(**changes: Any) -> dict[str, Any]:
    base = with_evidence(**changes)
    base["experiment_ledger"] = {
        "checkpoint": None,
        "entry_sha256": "4" * 64,
        "ledger_seq": 7,
        "store_id": "5" * 32,
    }
    return base


def run_ref(**changes: Any) -> dict[str, Any]:
    return {
        "eligible_at_pin": True,
        "role": "candidate",
        "run_id": RUN,
        "state_at_pin": "completed",
        **changes,
    }


# ----- canonical rendering -----


def test_rendering_is_canonical_and_round_trips() -> None:
    record = validate_record(document())
    data = render_record(record)
    assert render_record(validate_record(document())) == data
    parsed = parse_record_file(data, record.file_name)
    assert parsed.document == record.document
    text = data.decode("ascii")
    assert text.startswith("<!-- pmv gate record v1. Generated by pmv.gates; do not edit.")
    assert "| Decision | **PASS** |" in text
    assert text.endswith("```\n")
    assert record.file_name == f"gate_0_{RECORD_ID}.md"
    assert parse_file_name(record.file_name) == ("gate_0", RECORD_ID)


@pytest.mark.parametrize(
    "tamper",
    [
        lambda text: text.replace("**PASS**", "**FAIL**"),
        lambda text: text.replace("## Reviews", "## Reviews "),
        lambda text: text.replace('"decision":"pass"', '"decision":"fail"'),
        lambda text: text + "\n",
        lambda text: text.replace("<!-- pmv", "<!--  pmv"),
    ],
    ids=["summary", "heading", "json", "trailing", "header"],
)
def test_any_edit_to_the_file_is_detected(tamper: Callable[[str], str]) -> None:
    data = render_record(validate_record(document())).decode("ascii")
    with pytest.raises(GateRecordError):
        parse_record_file(tamper(data).encode("ascii"))


def test_file_name_must_match_the_record() -> None:
    data = render_record(validate_record(document()))
    with pytest.raises(GateRecordError, match="file name"):
        parse_record_file(data, f"gate_1_{RECORD_ID}.md")
    for bad in ("../gate_0_x.md", "gate_12_" + RECORD_ID + ".md", "gate_0_" + RECORD_ID + ".txt"):
        assert parse_file_name(bad) is None
    with pytest.raises(GateRecordError):
        record_file_name("gate_0", "../../etc")


