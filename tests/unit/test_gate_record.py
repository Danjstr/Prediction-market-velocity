# ----- lineage -----


def record(
    record_id: str, supersedes: tuple[str, str] | None = None, **overrides: Any
) -> GateRecord:
    stamp = record_id.split("_")[0]
    decided_at = (
        f"{stamp[0:4]}-{stamp[4:6]}-{stamp[6:8]}T{stamp[9:11]}:{stamp[11:13]}:"
        f"{stamp[13:15]}.{stamp[16:22]}Z"
    )
    prior = (
        None if supersedes is None else {"record_id": supersedes[0], "record_sha256": supersedes[1]}
    )
    return validate_record(
        document(record_id=record_id, decided_at=decided_at, supersedes=prior, **overrides)
    )


def rid(second: int, letter: str) -> str:
    return f"20261014T0315{second:02d}.000000Z_" + letter * 32


def member(item: GateRecord, *, committed: bool = True) -> LineageMember:
    return LineageMember(item, sha256_hex(render_record(item)), committed)


def test_a_valid_lineage_has_one_head() -> None:
    root = member(record(rid(1, "a")))
    second = member(record(rid(2, "b"), (rid(1, "a"), root.sha256)))
    third = member(record(rid(3, "c"), (rid(2, "b"), second.sha256)), committed=False)
    other = member(record(rid(4, "d"), gate_id="gate_1"))
    heads = verify_lineages([third, root, other, second])
    assert {key.gate_id: head.record.record_id for key, head in heads.items()} == {
        "gate_0": rid(3, "c"),
        "gate_1": rid(4, "d"),
    }


def test_lineage_violations_are_detected() -> None:
    root = member(record(rid(1, "a")))
    good = (rid(1, "a"), root.sha256)
    cases: list[tuple[list[LineageMember], str]] = [
        ([root, member(record(rid(2, "b")))], "more than one root"),
        (
            [root, member(record(rid(2, "b"), good)), member(record(rid(3, "c"), good))],
            "competing successors",
        ),
        ([root, member(record(rid(2, "b"), (rid(9, "f"), root.sha256)))], "does not exist"),
        ([root, member(record(rid(2, "b"), (rid(1, "a"), "0" * 64)))], "recorded hash"),
        ([root, member(record(rid(2, "b"), good, gate_id="gate_1"))], "another lineage"),
        (
            [member(record(rid(1, "a")), committed=False), member(record(rid(2, "b"), good))],
            "uncommitted",
        ),
    ]
    for members, message in cases:
        with pytest.raises(GateRecordError, match=message):
            verify_lineages(members)
    newer = member(record(rid(5, "e")))
    older = member(record(rid(4, "d"), (rid(5, "e"), newer.sha256)))
    with pytest.raises(GateRecordError, match="newer record"):
        verify_lineages([newer, older])


def test_cycles_are_rejected() -> None:
    first = record(rid(1, "a"), (rid(2, "b"), "0" * 64))
    second = record(rid(2, "b"), (rid(1, "a"), "0" * 64))
    members = [
        LineageMember(first, "0" * 64, True),
        LineageMember(second, "0" * 64, True),
    ]
    with pytest.raises(GateRecordError):
        verify_lineages(members)


