def test_schema_states_the_document_dirty_and_approval_rules() -> None:
    schema = json.loads(
        (Path(__file__).resolve().parents[2] / "schemas" / "gate_record_v1.json").read_text(
            encoding="ascii"
        )
    )
    definitions = schema["$defs"]
    assert definitions["review_document"]["properties"]["kind"]["enum"] == [
        kind.value for kind in gate_record.REVIEW_DOCUMENT_KINDS
    ]
    assert definitions["evidence_document"]["properties"]["kind"]["enum"] == [
        kind.value for kind in gate_record.EVIDENCE_DOCUMENT_KINDS
    ]
    properties = schema["properties"]
    for field in ("findings", "reviews"):
        assert properties[field]["items"]["properties"]["document"] == {
            "oneOf": [{"$ref": "#/$defs/review_document"}, {"type": "null"}]
        }
    assert properties["evidence"]["properties"]["documents"]["items"] == {
        "$ref": "#/$defs/evidence_document"
    }
    final = properties["final_decision"]["properties"]
    assert final["approval_requirement"] == {"const": "required"}
    assert final["approval_attested"] == {"const": True}
    assert [item.value for item in gate_record.ApprovalRequirement] == ["required"]
    dirty_rule = properties["project"]["oneOf"]
    assert dirty_rule == [
        {"properties": {"tree_dirty": {"const": False}, "dirty_tree_sha256": {"type": "null"}}},
        {
            "properties": {
                "tree_dirty": {"const": True},
                "dirty_tree_sha256": {"$ref": "#/$defs/sha256"},
            }
        },
    ]
